"""Regenerate the locks in ``requirements/locks/<target>.txt``.

    /path/to/pythonX.Y tools/lock.py [--check]            this platform's lock
    /path/to/python    tools/lock.py --cross [--check]    Windows and macOS locks

The first form runs with the interpreter the lock is for, on the platform it
is for, in a venv that has pip-tools 7.5.1.  It compiles ``requirements/cpu.in``
with hashes, then appends the vendored SDK wheel pinned by its SHA-256 (see
base.in for why pip-tools does not do that part).

``--cross`` writes the locks for the platforms no one here runs
(``CROSS_PLATFORMS`` x the Linux locks' Python minors) with uv 0.13.0's
cross-platform resolution, wheels only, each constrained to the Linux lock of
the same Python so every platform installs the same versions.  It needs
``uv`` importable (``pip install uv==0.13.0``).  Those locks are resolved,
not installed: a real install on each platform is still owed.

``--check`` writes nothing and exits 1 if a lock would change -- CI's "re-run
lock generation and fail on a diff".
"""

from __future__ import annotations

import hashlib
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SDK_WHEEL = "vizi_plugin_sdk-1.0.0-py3-none-any.whl"
#: Lock-name prefix -> uv's ``--python-platform``.
CROSS_PLATFORMS = {"windows-x86_64": "x86_64-pc-windows-msvc", "macos-arm64": "aarch64-apple-darwin"}
CROSS_MINORS = ("3.11", "3.13")


def target() -> str:
    os_name = {"Linux": "linux", "Darwin": "macos", "Windows": "windows"}[platform.system()]
    arch = {"x86_64": "x86_64", "AMD64": "x86_64", "arm64": "arm64", "aarch64": "arm64"}[platform.machine()]
    return f"{os_name}-{arch}-py{sys.version_info.major}{sys.version_info.minor}-cpu"


def generate() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "lock.txt"
        # Seeded with the current lock, pip-tools keeps its pins: regenerating
        # reproduces the lock unless an input changed, rather than taking
        # whatever PyPI published since.
        current = ROOT / "requirements" / "locks" / f"{target()}.txt"
        if current.exists():
            body = current.read_text(encoding="utf-8").split("vizi-plugin-sdk==", 1)[0]
            out.write_text("".join(line for line in body.splitlines(True) if not line.startswith("#")), encoding="utf-8")
        subprocess.run(
            [sys.executable, "-m", "piptools", "compile", "-q", "--generate-hashes", "--resolver=backtracking",
             "--strip-extras", "--no-emit-index-url", "--no-header", "--output-file", str(out),
             "requirements/cpu.in"],  # relative: the lock records it in "via" comments
            check=True, cwd=ROOT,
        )
        body = out.read_text(encoding="utf-8")
    return wrap(target(), body)


def wrap(name: str, body: str) -> str:
    """A lock's text: the header, what the resolver wrote, the vendored SDK."""
    digest = hashlib.sha256((ROOT / "vendor" / SDK_WHEEL).read_bytes()).hexdigest()
    head = (
        f"# {name}: generated by tools/lock.py from requirements/cpu.in; do not edit.\n"
        "# Install with: pip install --require-hashes --only-binary=:all: --find-links vendor -r <this file>\n"
    )
    sdk = f"vizi-plugin-sdk==1.0.0 \\\n    --hash=sha256:{digest}\n    # vendored: vendor/{SDK_WHEEL}\n"
    return head + body + sdk


def generate_cross(prefix: str, minor: str) -> tuple[str, str]:
    """``(lock name, text)`` for a platform resolved from here with uv."""
    name = f"{prefix}-py{minor.replace('.', '')}-cpu"
    linux = f"requirements/locks/linux-x86_64-py{minor.replace('.', '')}-cpu.txt"
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "lock.txt"
        subprocess.run(
            [sys.executable, "-m", "uv", "pip", "compile", "-q", "requirements/cpu.in",
             "--python-platform", CROSS_PLATFORMS[prefix], "--python-version", minor,
             "--generate-hashes", "--no-header", "--only-binary", ":all:",
             "-c", linux, "--output-file", str(out)],  # relative paths: the lock records them
            check=True, cwd=ROOT,
        )
        return name, wrap(name, out.read_text(encoding="utf-8"))


def main() -> int:
    if "--cross" in sys.argv[1:]:
        locks = [generate_cross(prefix, minor) for prefix in CROSS_PLATFORMS for minor in CROSS_MINORS]
    else:
        locks = [(target(), generate())]
    stale = 0
    for name, text in locks:
        path = ROOT / "requirements" / "locks" / f"{name}.txt"
        if "--check" in sys.argv[1:]:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{path.name} is stale: run tools/lock.py", file=sys.stderr)
                stale = 1
            else:
                print(f"{path.name} is current")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path}")
    return stale


if __name__ == "__main__":
    sys.exit(main())
